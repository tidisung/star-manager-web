const byFace=new Map(POOP_EFFECTS.map(row=>[row.suit+row.rank,row]));
export const REVIEW_STATUSES=["검수 전","미확정","확정"];
export function poopDefinition(state,suit,rank){const key=suit+rank;return state.poopDefinitions?.[key]||byFace.get(key);}
export function applyPoopEffect(card,state={}){
 if(card?.tier!=='poop')return card;
 const row=poopDefinition(state,card.poker?.suit,card.poker?.rank);
 if(!row)return card;
 card.name=row.effect;card.effect=row.effect;card.reviewStatus=row.reviewStatus;
 return card;
}
export function syncPoopEffects(state){
 // Only current physical cards and live previews change; historical promises stay immutable.
 for(const card of state.deck||[])applyPoopEffect(card,state);
 for(const offer of Object.values(state.swapOffers||{}))for(const card of offer.candidates||[])applyPoopEffect(card,state);
 if(state.auction?.card)applyPoopEffect(state.auction.card,state);
}

export function editPoopDefinition(state,input,actor,now){
 const {suit,rank,effect,reviewStatus,expectedVersion}=input;
 if(!byFace.has(suit+rank)||typeof effect!=='string'||!effect.trim()||effect.length>1000||!REVIEW_STATUSES.includes(reviewStatus))throw Error('번호·효과 문구·검수 상태를 확인해 주세요. 효과는 1~1000자로 입력해 주세요.');
 const before=poopDefinition(state,suit,rank);
 if(expectedVersion!==(before.version||0))throw Error('다른 관리자 화면에서 수정한 카드예요. 닫았다 다시 열어 최신 내용을 확인해 주세요.');
 state.poopDefinitions ||= {};
 const after={suit,rank,effect,reviewStatus,version:(before.version||0)+1,updatedBy:actor,updatedAt:now};
 state.poopDefinitions[suit+rank]=after;syncPoopEffects(state);return {before,after};
}
